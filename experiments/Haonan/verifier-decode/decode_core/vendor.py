#!/usr/bin/env python3
"""Vendor the shared metrics into decode_core/_deps/metrics/.

Mirrors ``m1-countdown-trellis/vendor_metrics.py``: copies the canonical
``_shared/metrics/*.py`` modules into ``decode_core/_deps/metrics/``, ensures the
package ``__init__.py`` markers exist (``decode_core/_deps/`` and
``decode_core/_deps/metrics/``), and writes ``decode_core/_deps/metrics/PROVENANCE.txt``
recording the sha256 of each canonical source file.

The vendored copy is GENERATED and must never be hand-edited. To change a metric: edit
``_shared/metrics/``, then re-run this script. The decoder itself does NOT import these
metrics; they are vendored here so the shared ``decode_core`` package is self-contained
for the harness that does.

Usage:
    python vendor.py
    python decode_core/vendor.py
(works from anywhere; paths are resolved relative to this file).
"""
from __future__ import annotations

import datetime
import hashlib
import shutil
from pathlib import Path

# The six canonical source files to vendor.
SOURCE_FILES = [
    "diversity.py",
    "coverage.py",
    "markov.py",
    "calibration.py",
    "passk.py",
    "__init__.py",
]

# This file lives at <verifier-decode>/decode_core/vendor.py.
HERE = Path(__file__).resolve().parent
# Canonical source: experiments/_shared/metrics/
#   from HERE=.../Haonan/verifier-decode/decode_core
#   up to .../experiments/ is: decode_core -> verifier-decode -> Haonan -> experiments
#   (3 parents), then _shared/metrics.
SRC_DIR = (HERE.parent.parent.parent / "_shared" / "metrics").resolve()
DEST_DIR = (HERE / "_deps" / "metrics").resolve()


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def main() -> int:
    if not SRC_DIR.is_dir():
        raise SystemExit(f"canonical source dir not found: {SRC_DIR}")

    # Ensure package dirs exist with __init__.py.
    deps_dir = DEST_DIR.parent
    deps_dir.mkdir(parents=True, exist_ok=True)
    (deps_dir / "__init__.py").touch(exist_ok=True)
    DEST_DIR.mkdir(parents=True, exist_ok=True)

    provenance_lines = []
    for name in SOURCE_FILES:
        src = SRC_DIR / name
        if not src.is_file():
            raise SystemExit(f"expected canonical source file missing: {src}")
        dest = DEST_DIR / name
        shutil.copy2(src, dest)
        provenance_lines.append(f"{name}  sha256={_sha256(src)}")

    # __init__.py is part of SOURCE_FILES, so the package marker is already in place
    # from the copy above; nothing else needed for DEST_DIR.

    stamp = datetime.datetime.now(datetime.timezone.utc).isoformat()
    provenance = (
        "# VENDORED metrics — GENERATED by vendor.py. Do not edit by hand.\n"
        f"# Canonical source: {SRC_DIR}\n"
        f"# Vendored at (UTC): {stamp}\n"
        "#\n"
        "# Each line: <source filename>  sha256=<sha256 of the canonical source>\n"
        + "\n".join(provenance_lines)
        + "\n"
    )
    (DEST_DIR / "PROVENANCE.txt").write_text(provenance)

    print(f"Vendored {len(SOURCE_FILES)} files:")
    print(f"  from {SRC_DIR}")
    print(f"  to   {DEST_DIR}")
    for line in provenance_lines:
        print(f"  {line}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
